// Question 32: Write a program to demonstrate the use of arithmetic, relational, and logical operators.
public class Question32 {
    public static void main(String[] args) {
        int a = 10, b = 5;
        System.out.println("Arithmetic: a + b = " + (a + b));
        System.out.println("Relational: a > b = " + (a > b));
        System.out.println("Logical: (a > b) && (b > 0) = " + ((a > b) && (b > 0)));
    }
}
