// q25: Write a program that demonstrates the use of Math.random(), Math.abs(), and Math.pow() from the java.lang package.
public class q25 {
    public static void main(String[] args) {
        System.out.println("Random Value: " + Math.random());
        System.out.println("Absolute Value of -10: " + Math.abs(-10));
        System.out.println("2 to the power 3: " + Math.pow(2, 3));
    }
}
